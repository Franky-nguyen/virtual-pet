/**
 * Build the SVG path the lights follow: it starts at the Evolve button, spirals
 * OUTWARD across the screen (the "dance"), then spirals INWARD into the pet
 * (the "tornado" that shrinks to nothing). Returns a path()-compatible string
 * in viewport coordinates (the particles live in the fixed full-screen overlay).
 * 
 * Enhanced with erratic, unpredictable movement patterns for a more sensual,
 * organic flow while maintaining the overall spiral trajectory.
 */
function generateTornadoPath(
  px: number, py: number, bx: number, by: number, vw: number, vh: number,
): string {
  const rBtn = Math.hypot(bx - px, by - py)
  const aBtn = Math.atan2(by - py, bx - px)
  const rOut = Math.hypot(vw, vh) * 0.5
  const DANCE_FRAC = 0.38
  const TOTAL_TURNS = 4
  const STEPS = 240 // Higher resolution for smoother erratic curves

  // Random seed for this path generation - creates unique chaos each evolution
  const seed = Math.random() * 1000
  const wiggleBase = 20 + Math.sin(seed) * 10
  const freqBase = 15 + Math.cos(seed * 0.5) * 8

  const segs: string[] = []
  for (let i = 0; i <= STEPS; i++) {
    const t = i / STEPS
    
    // Erratic timing with speed variations - some moments pause, others rush
    const speedVar = Math.sin(t * Math.PI * 4 + seed) * 0.12
      + Math.cos(t * Math.PI * 7 - seed * 0.3) * 0.08
    const erraticT = Math.max(0, Math.min(1, t + speedVar))
    
    // Spiral angle with organic wobble and sudden twists
    const spiralWobble = Math.sin(erraticT * Math.PI * 8 + seed) * 0.4
      + Math.cos(erraticT * Math.PI * 15 - seed) * 0.2
    const theta = aBtn + erraticT * TOTAL_TURNS * Math.PI * 2 + spiralWobble
    
    let r: number
    if (erraticT <= DANCE_FRAC) {
      // Outward dance phase - wild, sensual undulations
      const u = erraticT / DANCE_FRAC
      r = rBtn + (rOut - rBtn) * u
      
      // Multiple overlapping sine waves create unpredictable, organic movement
      const wave1 = Math.sin(erraticT * freqBase + seed) * wiggleBase * (1 - u * 0.5)
      const wave2 = Math.cos(erraticT * Math.PI * 12 - seed * 0.7) * (wiggleBase * 0.6) * (1 - u)
      const wave3 = Math.sin(erraticT * Math.PI * 20 + seed * 1.3) * 8 * Math.sin(u * Math.PI)
      r += wave1 + wave2 + wave3
      
      // Occasional sharp deviations for surprise movement
      const sharpTurn = Math.abs(Math.sin(erraticT * Math.PI * 6)) > 0.85 ? 15 : 0
      r += sharpTurn * Math.sin(erraticT * Math.PI * 30) * (1 - u)
      
    } else {
      // Tornado inward spiral - tighter but still chaotic
      const u = (erraticT - DANCE_FRAC) / (1 - DANCE_FRAC)
      r = rOut * (1 - u)
      
      // Spiraling inward with seductive undulations
      const tighten = Math.sin(erraticT * Math.PI * 16 + seed) * 12 * (1 - u)
      const swirl = Math.cos(erraticT * Math.PI * 22 - seed * 0.5) * 6 * Math.sin((1 - u) * Math.PI)
      r += tighten + swirl
      
      // Final approach - subtle attraction pull toward center
      if (u > 0.7) {
        const pull = (u - 0.7) * 20 * (1 - u)
        r -= pull
      }
    }
    
    // Lateral deviation perpendicular to spiral - creates S-curve weaving
    const lateralFreq = 10 + Math.sin(seed * 0.8) * 5
    const lateralAmp = 25 * (1 - erraticT) * Math.sin(erraticT * Math.PI)
    const lateral = Math.sin(erraticT * Math.PI * lateralFreq + seed * 1.5) * lateralAmp
    
    const x = px + Math.cos(theta) * r + Math.sin(theta) * lateral
    const y = py + Math.sin(theta) * r - Math.cos(theta) * lateral
    
    segs.push(`${i === 0 ? 'M' : 'L'} ${x.toFixed(1)} ${y.toFixed(1)}`)
  }
  return segs.join(' ')
}

