const EVOLVED_OVERLAYS = import.meta.glob('../assets/pets/evolved/overlay_*.png', { eager: true, query: '?inline', import: 'default' }) as Record<string, string>

/** Sprite metadata for a single animation frame sheet. */
interface SpriteSheet {
  url: string
  frames: number
  /** Optional floating accessory overlay stacked on top of `url` (evolved only). */
  overlayUrl?: string
}

/**
 * Frame sizes per animation (base dog).
 * Most animations use 64×64px frames, but Walk uses 48×48px (6 frames = 288px wide).
 */
const FRAME_SIZES: Record<AnimationState, number> = {
  Idle: 64,
  Walk: 48,
  Hurt: 64,
  Death: 64,
  Attack: 64,
  Evolution: 64,
}

/**
 * Frame pixel sizes per animation for the EVOLVED adult dog.  All evolved
 * sheets use 64×64px tiles on a 64px-tall strip (confirmed by pixel inspection
 * of each source file).  The on-screen render size is also 64px, so no upscaling
 * is needed — the pet stays the same pixel size as the puppy.
 */
const EVOLVED_FRAME_SIZES: Record<AnimationState, number> = {
  Idle: 64,
  Walk: 64,
  Hurt: 64,
  Death: 64,
  Attack: 64,
  Evolution: 64,
}

/**
 * Look up the sprite sheet URL for a given animation + accessory combination.
 * If `evolved` is true, routes to the evolved composite sheets when an accessory
 * is equipped (evolved_idle_crown.png etc.) — these have the accessory baked
 * directly into the sprite at the correct size and position.
 * For the non-evolved pet, falls back to the original base dog sheets.
 */
function getSpriteUrl(animation: AnimationState, accessory: AccessoryType, evolved: boolean): SpriteSheet {
  if (evolved) {
    // When an accessory is equipped, use the baked composite sheet directly.
    // These have the accessory drawn onto the correct-sized dog at the right position.
    if (accessory !== 'none') {
      const compositePath = `../assets/pets/evolved/evolved_${animation.toLowerCase()}_${accessory}.png`
      const compositeUrl = EVOLVED_SPRITES[compositePath]
      if (compositeUrl) return { url: compositeUrl, frames: EVOLVED_ANIMATION_FRAMES[animation] }
    }
    // No accessory or composite not found — use the base evolved sprite
    const basePath = `../assets/pets/evolved/evolved_${animation.toLowerCase()}.png`
    const baseUrl = EVOLVED_SPRITES[basePath]
    if (baseUrl) return { url: baseUrl, frames: EVOLVED_ANIMATION_FRAMES[animation] }
    // Fallback: evolved Idle (guaranteed to exist)
    const idleUrl = EVOLVED_SPRITES['../assets/pets/evolved/evolved_idle.png'] ?? ''
    return { url: idleUrl, frames: EVOLVED_ANIMATION_FRAMES['Idle'] }
  }

  const frames = ANIMATION_FRAMES[animation]

  if (accessory !== 'none') {
    const accessorized = `../assets/pets/${animation}_${accessory}.png`
    const url = ALL_SPRITES[accessorized]
    if (url) return { url, frames }
    const base = `../assets/pets/${animation}.png`
    const baseUrl = ALL_SPRITES[base]
    if (baseUrl) return { url: baseUrl, frames }
  } else {
    const base = `../assets/pets/${animation}.png`
    const url = ALL_SPRITES[base]
    if (url) return { url, frames }
  }

  // Ultimate fallback: Idle.png (guaranteed to exist)
  const idleUrl = ALL_SPRITES['../assets/pets/Idle.png'] ?? ''
  return { url: idleUrl, frames: ANIMATION_FRAMES['Idle'] }
}

