/** How long the lights dance/swirl before the flash + evolution sprite trigger. */
const PARTICLES_MS = 5800
/** Overlay fade-in / fade-out duration (matches `.evolve-overlay`). */
const OVERLAY_FADE_MS = 400
/** Duration of the explosion burst from the Evolve button. */
const EXPLODE_MS = 700
/** Delay before the tornado phase begins (right after the explosion scatters). */
const TORNADO_DELAY_MS = 700
/** Time each light takes to traverse the tornado path. */
const TRAVERSE_MS = 3600
/** Launch stagger between consecutive lights (the "follow each other" effect). */
const STAGGER_MS = 40
/** Number of magical lights spawned per evolution. */
const PARTICLES_COUNT = 30

interface EvolveParticle {
  id: number
  size: number
  color: string
  ex: number          // explosion target offset from the button (x, px)
  ey: number          // explosion target offset from the button (y, px)
}

const PARTICLE_COLORS = ['#fff7cc', '#ffd76e', '#ffffff', '#ffec9e', '#ffe28a']

/**
 * Build the SVG path the lights follow: it starts at the Evolve button, spirals
 * OUTWARD across the screen (the "dance"), then spirals INWARD into the pet
 * (the "tornado" that shrinks to nothing). Returns a path()-compatible string
 * in viewport coordinates (the particles live in the fixed full-screen overlay).
 */
function generateTornadoPath(
  px: number, py: number, bx: number, by: number, vw: number, vh: number,
): string {
  const rBtn = Math.hypot(bx - px, by - py)
  const aBtn = Math.atan2(by - py, bx - px)
  const rOut = Math.hypot(vw, vh) * 0.5
  const DANCE_FRAC = 0.38
  const TOTAL_TURNS = 4        // ~1.5 turns out (dance) + ~2.5 turns in (tornado)
  const STEPS = 180

  const segs: string[] = []
  for (let i = 0; i <= STEPS; i++) {
    const t = i / STEPS
    const theta = aBtn + t * TOTAL_TURNS * Math.PI * 2
    let r: number
    if (t <= DANCE_FRAC) {
      const u = t / DANCE_FRAC
      r = rBtn + (rOut - rBtn) * u
      r += Math.sin(t * 22) * 18 * (1 - u)   // organic dance wiggle
    } else {
      const u = (t - DANCE_FRAC) / (1 - DANCE_FRAC)
      r = rOut * (1 - u)
    }
    const x = px + Math.cos(theta) * r
    const y = py + Math.sin(theta) * r
    segs.push(`${i === 0 ? 'M' : 'L'} ${x.toFixed(1)} ${y.toFixed(1)}`)
  }
  return segs.join(' ')
}

